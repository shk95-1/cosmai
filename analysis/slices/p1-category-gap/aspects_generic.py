def build(category):
    sp = SPECIFIC.get(category, {})
    asp = dict(sp); asp.update({k: v for k, v in GENERIC.items() if k not in asp})
    # 카테고리 전용 항목이 같은 표현을 먼저 가져가도록 앞에 둔다 (dict 삽입 순서)
    rx = {k: re.compile(v) for k, v in asp.items()}
    return rx, (GENERIC_NEUTRAL | {k for k in sp if k in SPECIFIC_NEUTRAL})

_cache = {}
def classify(sentence, category):
    if category not in _cache: _cache[category] = build(category)
    rx, neutral = _cache[category]
    P.ASPECT_RE, P.NEUTRAL_ASPECTS = rx, neutral
    a, p, why = P.classify(sentence)
    return (a.rstrip('~') if a else a), p, why


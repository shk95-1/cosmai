def classify_sentence(s):
    """returns (cls, marker)"""
    if PAST_LAUNCH.search(s) and not re.search(r'재출시|다시 출시|또 출시|도 출시|출시 ?(해 ?주(세|시면|실|셨으면|길|면)|했으면|좀|되었으면|됐으면)', s):
        pass  # fact statement about a launch; fall through to b/c checks without LAUNCH
        launch = None
    else:
        launch = LAUNCH.search(s)
    if re.search(r'돈쭐|교과서|정신 ?차리|혼 ?내|화 ?내|짜증 ?내|성질 ?내|티 ?내|빛 ?내|소리 ?내|열 ?내|겟잇뷰티|방송에|출연|나와주세요', s): launch = None
    if launch and not CONTENT.search(s):
        return 'a', launch.group(0)
    pq = PRODUCT_Q.search(s)
    if pq and not CONTENT_NOMARKET.search(s) and not re.search(r'추천|어디|뭐|무슨|어떤|답이|방법', s):
        return 'a', pq.group(0)
    if launch and CONTENT.search(s):
        # "X 출시해주세요 리뷰도" — launch verb dominates if it is a make/launch verb
        if re.search(r'출시 ?(해 ?주|했으면|좀|되었으면|됐으면|해줘)|나왔으면|내 ?줬으면|재출시|단종', s) and not re.search(r'컨텐츠|콘텐츠|영상|채널|편\b', s):
            return 'a', launch.group(0)
    bm = is_b(s)
    if bm:
        return 'b', bm
    w = WISH_ANY.search(s)
    if w and not NOT_C.search(s):
        return 'c', w.group(0)
    return 'n', ''

ORDER = {'a': 0, 'b': 1, 'c': 2, 'n': 3}
def classify(text):
    best = ('n', '', '')
    for s in sentences(text):
        c, m = classify_sentence(s)
        if ORDER[c] < ORDER[best[0]]:
            best = (c, m, s)
